const LANG_STORAGE_KEY = 'cc_lang';

function getCurrentLang() {
  return localStorage.getItem(LANG_STORAGE_KEY) || 'uz-lat';
}

function setLang(lang) {
  if (!TRANSLATIONS[lang]) return;
  localStorage.setItem(LANG_STORAGE_KEY, lang);
  document.documentElement.setAttribute('lang', lang === 'ru' ? 'ru' : 'uz');
  applyTranslations();
}

function _t(key) {
  const lang = getCurrentLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS['uz-lat'];
  return dict[key] || key;
}

function applyTranslations() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    el.textContent = _t(el.getAttribute('data-i18n'));
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    el.placeholder = _t(el.getAttribute('data-i18n-placeholder'));
  });
}

window.TRANSLATIONS = TRANSLATIONS;
window.getCurrentLang = getCurrentLang;
window.setLang = setLang;
window._t = _t;
window.applyTranslations = applyTranslations;
